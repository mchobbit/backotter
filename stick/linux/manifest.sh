# What ImgTest2 records of the Linux image (typed by boot-test.py --manifest, a line
# at a time; keep each under 300 characters).  Each `mf KEY COMMAND` prints one line,
# "BKO-MF KEY VALUE", VALUE "-" when COMMAND printed nothing.  kernel, zfs, tool:* and
# pkg:* are the storage fields, whose change makes the panel due.
mf kernel 'uname -r'
mf zfs 'zfs version | head -n 1'
mf image_id 'sed -n "s/.*\"image_id\": \"\([^\"]*\)\".*/\1/p" /cdrom/.disk/backotter.json | head -n 1'
mf bin:restic-bko 'f=$(command -v restic-bko) && sha256sum "$f" | cut -d" " -f1'
