"""GNU Guix System (guix15, guix15-bios; docs/design/guix.md): a store
system, as NixOS, whose generations each carry their own boot parameters,
and whose GRUB load never reinstalls (holt/src/store.rs: the store has no
GRUB).  Before this module its dumps were generic Linux's.

What load does on a restored Guix (holt/src/load/commands.rs, the store
system arms), and so what a drift may touch:
- UEFI: nothing runs in the chroot.  grubx64.efi comes back with the ESP
  (and its EFI/BOOT/BOOTX64.EFI copy), grub.cfg and every generation's
  kernel and initrd with / (they live in /gnu/store); only the boot entry
  is made.  The ESP itself stays put (edits.movable: the source's NVRAM
  entry names it by start and number, guix15's Boot0001); --no-nvram and
  --removable are drawn (store_removable copies the image to the fallback),
  so guix15's tier 2 cases are those.
- BIOS: the rescue's grub-bios-setup writes the source's own boot.img and
  core.img (restored in /boot/grub/i386-pc) at the new disk's sector
  addresses: the BIOS boot partition may move, and grow or shrink within
  what core.img needs.
- grub.cfg (regenerated by each reconfigure, never by load) finds / by
  UUID (guix15) or label (guix15-bios), and boots root= by the same: kept
  by every edit (rule 3 refuses a changed identifier).  Btrfs's subvolumes
  @, @home and @gnu are made with their IDs and paths, so the kernels'
  /@gnu/store/... paths still resolve.
- The swap is activated by Shepherd from config.scm's swap-devices.

The family's own rules:
- Quirk unrecorded-names: refuses renumber and swap_order of a partition
  the dump can't say how Guix names.  (a) A swap partition, always: Guix
  writes no swap line to /etc/fstab (docs/design/guix.md, "the guests"),
  and the dump's swaps are /proc/swaps' kernel paths, so a config.scm
  swap-space target of "/dev/vda2" is invisible to rule 3.  Our guests
  name theirs by UUID; a dump gap all the same.  (b) With two or more
  generations, a partition holding anything mounted other than / and the
  store: each older generation mounts its own file-systems from its own
  store /etc/fstab, which the dump doesn't record (boot.store records each
  one's root device and kernel arguments, which rule 3 reads below).  A
  dump gap: with each generation's fstab recorded, rule 3 could check them.
- Quirk store-initrd: each generation's initrd is a store item built from
  its configuration's initrd modules and file systems, and load rebuilds
  none: a drift may not add or drop a filesystem type or stack layer.  No
  phase 1 edit does (holds by construction, as for NixOS).
- Rule 3 texts: every generation's kernel arguments, root and store devices,
  and grub.cfg's searches and roots (boot.store); the generic texts add
  fstab, the command line and grub.cfg's default linux line.

What isn't excluded, on purpose:
- Renumbering /'s partition on UEFI.  Guix's grub-install (grub-efi-
  bootloader) embeds the prefix "(,gptN)/boot/grub" in grubx64.efi, the
  partition by number, since the ESP is on /boot's disk; grub.cfg's search
  by UUID comes only after the prefix has loaded normal.mod.  load keeps
  the image as restored, so a renumbered / would end in grub rescue.  That
  is load's to rebuild, as it renews a fallback loader's (BackShot2's
  fail-002): a bko-holt finding, not a drift Guix can't have.
- On BIOS the same prefix is in core.img; renumbering /boot/grub's
  partition is refused there by the generic rule 3 already (grub.cfg has
  no search UUIDs: guix15-bios searches by label), so it isn't drawn.

- Content drift: recipe guix-small-1 (alpine-small-1's shape: hard links,
  sparse files, nodes, xattrs, ACLs, a deep tree past PATH_MAX) on / at
  /srv/bs2: ext4 on guix15, Btrfs's @ on guix15-bios (the first Btrfs root
  the content drift reaches).
- versions(): the dump's packages are the system profile's manifest
  (e2fsprogs, btrfs-progs, dosfstools); util-linux isn't recorded, so
  sfdisk's rows are the oldest.
- tier0 "chroot": Guix's tools are in the store, reached through the system
  profile (/var/guix/profiles/system/profile/{sbin,bin}), which tier0.Tools
  puts on the chroot's PATH after the usual directories.  /run/current-system
  isn't needed (Guix mounts no tmpfs on /run, but the copy is of a shut-down
  guest).
"""

from .. import dumpx
from .base import Family, Quirk, holds_something, layers_quirk, os_id, walk_moves

RECIPES = {
    # alpine-small-1's shape (the planter's knobs), for Guix's / (ext4 or Btrfs's @).
    "guix-small-1": {"files": 60, "large": 24 << 20, "deep": 1, "deep_bytes": 4300, "links": 8, "symlinks": 12, "names": 10, "nodes": 4},
}
RECIPE = "guix-small-1"


def store(dump):
    return (dump.get("boot") or {}).get("store") or {}


def generations(dump):
    """The generation numbers boot.store lists."""
    return {int(g["number"]) for g in store(dump).get("generations") or [] if g.get("number") is not None}


def store_texts(dump):
    """Rule 3: what each generation boots with (kernel arguments, root and
    store devices) and grub.cfg's searches and roots."""
    st = store(dump)
    out = []
    for g in st.get("generations") or []:
        out += [str(a) for a in g.get("kernel_arguments") or []]
        for k in ("root_device", "store_device"):
            v = g.get(k)
            if isinstance(v, dict):
                out.append(str(v.get("value") or ""))
            elif v:
                out.append(str(v))
    cfg = st.get("grub_cfg") or {}
    out += [str(s.get("value") or "") for s in cfg.get("searches") or []]
    out += [str(r) for r in cfg.get("roots") or []]
    return out


def _mounted_here(d, p):
    """The mount targets on partition P (directly, or on a device built on it)."""
    names = {p["name"]} | {c["name"] for c in dumpx.children(d, p["name"])}
    return {str(m.get("target") or "") for m in dumpx.storage(d).get("mounts") or [] if m.get("device") in names}


def check_names(source, drifted, edits):
    out = []
    many = len(generations(source)) >= 2
    for e, dk, p in walk_moves(source, edits):
        typ = (p.get("content") or {}).get("type")
        if typ == "swap":
            out.append((3, f"{e['op']} {p['name']}: Guix activates its swap from config.scm's swap-devices, which the dump "
                           f"doesn't record (no swap line in /etc/fstab), so a swap named by device path can't be ruled out"))
            continue
        if many and holds_something(source, p):
            other = sorted(t for t in _mounted_here(source, p) if t not in ("/", "/gnu", "/gnu/store"))
            if other or not _mounted_here(source, p):
                out.append((3, f"{e['op']} {p['name']}: Guix lists {len(generations(source))} generations, and the dump records "
                               f"only the current one's /etc/fstab ({', '.join(other) or 'what it holds'})"))
    return out


FAMILY = Family(
    name="guix",
    piece="bs2-guix",
    priority=10,
    matches=lambda source, dump: os_id(dump) == "guix",
    quirks=[
        Quirk("unrecorded-names", "Guix's swap-devices and its older generations' file-systems aren't in the dump", check_names),
        layers_quirk("Guix's initrd", "each generation's initrd is a store item built from its configuration, not rebuilt by load"),
    ],
    config_texts=store_texts,
    recipes=RECIPES,
    content=lambda dump, fstype: RECIPE,
    tier0="chroot",
)
